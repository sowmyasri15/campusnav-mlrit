export const getEmergencyExits = () =>
  campusLocations.filter((l) => l.type === 'exit');

export const haversineDistance = (lat1, lng1, lat2, lng2) => {
  const R = 6371;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLng = ((lng2 - lng1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLng / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
};

export const findNearestExit = (lat, lng) => {
  const exits = getEmergencyExits();
  if (exits.length === 0) return null;
  return exits.reduce((nearest, exit) => {
    const d = haversineDistance(lat, lng, exit.lat, exit.lng);
    return d < haversineDistance(lat, lng, nearest.lat, nearest.lng) ? exit : nearest;
  }, exits[0]);
};

export const fuzzyMatch = (query, locations) => {
  const q = query.toLowerCase().trim();
  return locations.find(
    (l) =>
      l.name.toLowerCase().includes(q) ||
      l.type.toLowerCase().includes(q) ||
      q.includes(l.name.toLowerCase().split(' ')[0])
  );
};
